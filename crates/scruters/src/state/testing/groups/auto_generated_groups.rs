pub(crate) use self::auto_generated_group_metadata::AutoGeneratedGroupMetadata;
use super::{AnyGroup, GroupKey, GroupName};
use crate::{
    cargo::{CargoCommandArgs, CargoTestArgs},
    command::spawn_command,
    state::testing::{
        groups::Group,
        tests::{Test, TestKind},
    },
};
use alloc::{borrow::Cow, collections::VecDeque};
use auto_generated_group_metadata::TargetKind;
use color_eyre::{eyre::Context, Result};
use core::{
    cmp::Ordering,
    hash::{Hash, Hasher},
};
use futures::stream::select;
use if_chain::if_chain;
use tokio::io::{AsyncBufReadExt as _, BufReader};
use tokio_stream::{wrappers::LinesStream, StreamExt};
use tokio_util::sync::CancellationToken;

pub mod auto_generated_group_metadata;

#[derive(Debug)]
pub(crate) struct AutoGeneratedGroup {
    name: GroupName,
    metadata: AutoGeneratedGroupMetadata,
    pub(super) tests: VecDeque<Test>,
}

impl AutoGeneratedGroup {
    fn new(
        name: GroupName,
        metadata: AutoGeneratedGroupMetadata,
        mut tests: VecDeque<Test>,
    ) -> Self {
        tests.make_contiguous().sort_unstable();
        Self { name, metadata, tests }
    }

    pub(in crate::state::testing) fn empty_from_metadata(
        metadata: AutoGeneratedGroupMetadata,
    ) -> Self {
        Self::new(
            GroupName::from(&metadata),
            metadata,
            VecDeque::new(),
        )
    }

    #[allow(clippy::too_many_lines)]
    pub(in crate::state::testing) async fn from_metadata(
        metadata: AutoGeneratedGroupMetadata,
        cancellation_token: CancellationToken,
    ) -> Result<Option<Self>> {
        const TEST_LINE_SUFFIX: &str = ": test";
        const TEST_LINE_SUFFIX_LEN: usize =
            TEST_LINE_SUFFIX.len();

        if let TargetKind::Tests(target_names) =
            &metadata.target_kind
        {
            let mut tests =
                VecDeque::with_capacity(target_names.len());

            #[allow(clippy::iter_over_hash_type)]
            for target_name in target_names {
                tests.push_back(Test {
                    package_name: metadata
                        .package_name
                        .clone(),
                    kind: TestKind::IntegrationTarget {
                        target_name: target_name.clone(),
                    },
                });
            }

            let group = Self::new(
                GroupName::from(&metadata),
                metadata,
                tests,
            );

            Ok(Some(group))
        } else if let TargetKind::Examples(target_names) =
            &metadata.target_kind
        {
            let mut tests =
                VecDeque::with_capacity(target_names.len());

            #[allow(clippy::iter_over_hash_type)]
            for target_name in target_names {
                tests.push_back(Test {
                    package_name: metadata
                        .package_name
                        .clone(),
                    kind: TestKind::ExampleTarget {
                        target_name: target_name.clone(),
                    },
                });
            }

            let group = Self::new(
                GroupName::from(&metadata),
                metadata,
                tests,
            );

            Ok(Some(group))
        } else {
            let command = CargoTestArgs {
                args: metadata.to_args().map(Into::into),
                color: false,
                list: true,
                ..Default::default()
            }
            .into_command();

            let (stdout, stderr) = spawn_command(
                command,
                cancellation_token.clone(),
            )
            .wrap_err(
                "Failed to run command listing tests",
            )?;

            let mut reader = select(
                LinesStream::new(
                    BufReader::new(stdout).lines(),
                ),
                LinesStream::new(
                    BufReader::new(stderr).lines(),
                ),
            );

            let mut test_names = Vec::new();

            #[allow(
                clippy::integer_division_remainder_used
            )]
            loop {
                tokio::select! {
                    () = cancellation_token.cancelled() => {
                        return Ok(None);
                    }
                    maybe_line = reader.next() => {
                        if let Some(mut line) = maybe_line.transpose().wrap_err("Failed to read line from command output")? {
                            if_chain! {
                                if line.ends_with(TEST_LINE_SUFFIX);
                                let _ = line.split_off(line.len().saturating_sub(TEST_LINE_SUFFIX_LEN));
                                if !line.is_empty() && !line.contains(' ');
                                then {
                                    test_names.push(line);
                                }
                            }
                        } else {
                            let mut tests = VecDeque::with_capacity(test_names.len());
                            for test_name in test_names {
                                match &metadata.target_kind {
                                    TargetKind::Bin(target_name) => {
                                        tests.push_back(Test {
                                            package_name: metadata.package_name.clone(),
                                            kind: TestKind::BinTest {
                                                target_name: target_name.clone(),
                                                test_name
                                            }
                                        });
                                    }
                                    TargetKind::Lib(_) => {
                                        tests.push_back(Test {
                                            package_name: metadata.package_name.clone(),
                                            kind: TestKind::LibTest {
                                                test_name
                                            }
                                        });
                                    }
                                    TargetKind::Test(target_name) => {
                                        tests.push_back(Test {
                                            package_name: metadata.package_name.clone(),
                                            kind: TestKind::IntegrationTest {
                                                target_name: target_name.clone(),
                                                test_name
                                        }});
                                    }
                                    TargetKind::Example(target_name) => {
                                        tests.push_back(Test {
                                            package_name: metadata.package_name.clone(),
                                            kind: TestKind::ExampleTest {
                                                target_name: target_name.clone(),
                                                test_name
                                            }
                                        });
                                    },
                                    TargetKind::Tests(_) | TargetKind::Examples(_) => {
                                        unreachable!("Expected a single target name");
                                    }
                                }
                            }

                            if let TargetKind::Example(target_name) = &metadata.target_kind {
                                tests.push_front(
                                    Test {
                                        package_name: metadata.package_name.clone(),
                                        kind: TestKind::ExampleMain {
                                            target_name: target_name.clone(),
                                        },
                                    }
                                );
                            }

                            let group = Self::new(
                                GroupName::from(&metadata),
                                metadata,
                                tests,
                            );

                            return Ok(Some(group));
                        }
                    }
                }
            }
        }
    }
}

impl AnyGroup for AutoGeneratedGroup {
    fn name(&self) -> Cow<'_, GroupName> {
        Cow::Borrowed(&self.name)
    }

    fn tests(&self) -> &[Test] {
        self.tests.as_slices().0
    }

    fn update_group(&mut self, group: Group) {
        debug_assert!(
            self.name.eq(group.name().as_ref()),
            "Expected group names to be equal"
        );

        #[allow(clippy::panic)]
        let Group::AutoGenerated(group) = group else {
            panic!("Expected an auto-generated group");
        };

        self.metadata = group.metadata;
        self.tests = group.tests;

        let auto_generated_tests = match &self
            .metadata
            .target_kind
        {
            TargetKind::Bin(_)
            | TargetKind::Lib(_)
            | TargetKind::Test(_) => vec![],
            TargetKind::Tests(target_names) => target_names
                .iter()
                .map(|target_name| Test {
                    package_name: self
                        .metadata
                        .package_name
                        .clone(),
                    kind: TestKind::IntegrationTarget {
                        target_name: target_name.clone(),
                    },
                })
                .collect(),
            TargetKind::Examples(target_names) => {
                target_names
                    .iter()
                    .map(|target_name| Test {
                        package_name: self
                            .metadata
                            .package_name
                            .clone(),
                        kind: TestKind::ExampleTarget {
                            target_name: target_name
                                .clone(),
                        },
                    })
                    .collect()
            }
            TargetKind::Example(target_name) => {
                vec![Test {
                    package_name: self
                        .metadata
                        .package_name
                        .clone(),
                    kind: TestKind::ExampleMain {
                        target_name: target_name.clone(),
                    },
                }]
            }
        };

        for test in auto_generated_tests {
            match self.tests.binary_search(&test) {
                Ok(_) => {}
                Err(index) => {
                    self.tests.insert(index, test);
                }
            }
        }

        _ = self.tests.make_contiguous();
    }

    fn to_cargo_command_args(
        &self,
    ) -> CargoCommandArgs<'_> {
        let args = self.metadata.to_args().map(Into::into);
        CargoTestArgs { args, ..CargoTestArgs::default() }
            .into()
    }

    fn as_group_key(&self) -> GroupKey<'_> {
        GroupKey::AutoGenerated(Cow::Borrowed(
            &self.metadata,
        ))
    }
}

#[allow(clippy::missing_trait_methods)]
impl PartialEq for AutoGeneratedGroup {
    fn eq(&self, other: &Self) -> bool {
        self.metadata == other.metadata
    }
}

#[allow(clippy::missing_trait_methods)]
impl Eq for AutoGeneratedGroup {}

#[allow(clippy::missing_trait_methods)]
impl Hash for AutoGeneratedGroup {
    fn hash<H: Hasher>(&self, state: &mut H) {
        self.metadata.hash(state);
    }
}

#[allow(clippy::missing_trait_methods)]
impl PartialOrd for AutoGeneratedGroup {
    fn partial_cmp(
        &self,
        other: &Self,
    ) -> Option<Ordering> {
        Some(self.cmp(other))
    }
}

#[allow(clippy::missing_trait_methods)]
impl Ord for AutoGeneratedGroup {
    fn cmp(&self, other: &Self) -> Ordering {
        self.metadata.cmp(&other.metadata)
    }
}
